# 上面重复 key 以最后写入为准，删掉 OVERRIDES 中误加进 FAM 的空条目
OVERRIDES = {k: v for k, v in OVERRIDES.items() if v[0]}

def clean_label(label, key):
    s = re.sub(r"（[^）]*）\s*$", "", str(label or "")).strip()
    return s or key

def default_text(f):
    d = f.get("defaultValue")
    if d is None or d == "":
        return ""
    if isinstance(d, bool):
        return "默认开启" if d else "默认关闭"
    if isinstance(d, float) and d == int(d) and abs(d) < 1e6:
        return f"默认 {int(d)}"
    return f"默认 {d}"

def sentences(desc):
    parts = re.split(r"(?<=[。！？!?])", str(desc or "").strip())
    return [p for p in parts if p.strip()]

def build_standard(f, ov):
    key, label = f["key"], f.get("label") or f["key"]
    desc = str(f.get("desc") or "").strip()
    dt = default_text(f)
    if ov:
        summary, effect, wtu, awd = ov[0], ov[1], ov[2], ov[3]
        optdesc = ov[4] if len(ov) > 4 else None
        # 容错：模板第 4/5 位可能直接给了 optionDescriptions dict
        for name, slot in (("summary", 0), ("effect", 1), ("wtu", 2), ("awd", 3)):
            if isinstance(ov[slot], dict):
                optdesc = {**(optdesc or {}), **ov[slot]}
                if slot == 0:
                    summary = ""
                elif slot == 1:
                    effect = ""
                elif slot == 2:
                    wtu = ""
                else:
                    awd = ""
        lab = clean_label(f.get("label"), key)
        summary = str(summary).replace("{label}", lab)
        effect = str(effect).replace("{label}", lab)
        wtu = str(wtu).replace("{label}", lab)
        awd = str(awd).replace("{label}", lab)
        if dt and "{default}" in (summary + effect):
            summary = summary.replace("{default}", dt.replace("默认 ", "")).replace("（默认 ）", "")
            effect = effect.replace("{default}", dt.replace("默认 ", "")).replace("（默认 ）", "")
    else:
        ss = sentences(desc)
        summary = ss[0] if ss else f"{label}。对应训练配置键 {key}" + (f"，{dt}" if dt else "。")
        effect = "".join(ss[1:]).strip() if len(ss) > 1 else (
            f"写入训练配置 {key}，由训练后端在相应阶段消费。")
        wtu, awd = heuristic_guidance(f, dt)
        optdesc = None
    # select 且有选项：补充选项说明（无手写时列出可选值）
    if f.get("type") == "select" and f.get("options"):
        opts = [str(o if not isinstance(o, dict) else o.get("value", o)) for o in f["options"]]
        if not optdesc:
            optdesc = {}
        for o in opts:
            optdesc.setdefault(o, "")
        optdesc = {k: v for k, v in optdesc.items() if v}
        if optdesc:
            pass
    std = {"summary": summary, "effect": effect, "whenToUse": wtu, "avoidWhen": awd}
    return std

def heuristic_guidance(f, dt):
    t = f.get("type")
    if t == "boolean":
        d = f.get("defaultValue")
        if d:
            return ("默认开启，适合大多数场景。", "排查问题想回到原始行为时可关闭对比。")
        return ("需要该行为时开启。", "默认关闭；不确定影响时先保持关闭观察。")
    if t in ("file", "folder"):
        return ("路径留空时走默认解析/该功能不启用。", "填错路径会在预检或启动时报错，注意路径有效性。")
    if dt:
        return (f"{dt}，无明确目标时保持默认。", "一次只改一项，便于归因效果。")
    return ("按训练目标与显存预算调整。", "一次只改一项，便于归因效果。")

def main():
    written = 0
    skipped_hidden = 0
    for f in targets:
        key = f["key"]
        ov = OVERRIDES.get(key)
        fam_ov = None
        for pfx, tpl in FAM.items():
            if key.startswith(pfx):
                fam_ov = tpl
                break
        use = ov or fam_ov
        entry = {
            "key": key,
            "title": clean_label(f.get("label"), key),
            "category": category_of(f),
            "appliesTo": sorted(set(f.get("types") or [])),
            "standard": build_standard(f, use),
            "advanced": None,
            "relatedConfigs": [],
        }
        # select 选项说明
        if f.get("type") == "select" and f.get("options"):
            optdesc = (use[4] if use and len(use) > 4 else None) or {}
            for o in f["options"]:
                v = str(o if not isinstance(o, dict) else o.get("value", o))
                if v not in optdesc:
                    optdesc[v] = ""
            optdesc = {k: v for k, v in optdesc.items() if v}
            if optdesc:
                entry["standard"]["optionDescriptions"] = optdesc
        (SOT / f"{key}.json").write_text(
            json.dumps(entry, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n"
        )
        written += 1
    print(f"written {written} entries to {SOT}")

if __name__ == "__main__":
    main()
