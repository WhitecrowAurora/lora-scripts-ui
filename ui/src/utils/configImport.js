export function isLulynxToml(text) {
  // Our writer already identifies the format; shared Kohya option values cannot
  // override that identity or send a native file through a lossy foreign map.
  return /^\s*# Generated by (?:LoRA ReScripts UI|lulynx)\s*$/m.test(String(text));
}

// External importers return backend contract names. Translate only keys absent
// from this UI schema, keeping an explicitly supplied UI value authoritative.
const BACKEND_UI_KEYS = Object.freeze({
  base_model_path: 'pretrained_model_name_or_path',
  resume_path: 'resume',
  network_weights_path: 'network_weights',
  anima_qwen3_path: 'qwen3',
  anima_t5_tokenizer_path: 't5_tokenizer_path',
  anima_t5_max_token_length: 't5_max_token_length',
  anima_qwen3_max_token_length: 'qwen3_max_token_length',
  anima_llm_adapter_path: 'llm_adapter_path',
  anima_dit_adapter_path: 'dit_adapter_path',
  anima_attn_mode: 'attention_backend',
  attn_mode: 'attention_backend',
  torch_compile_backend: 'dynamo_backend',
});

export function normalizeImportedConfig(config, getFieldDefinition) {
  const result = { ...config };
  for (const [source, target] of Object.entries(BACKEND_UI_KEYS)) {
    if (result[source] !== undefined && !getFieldDefinition(source) && getFieldDefinition(target)) {
      if (result[target] === undefined) result[target] = result[source];
      delete result[source];
    }
  }
  return result;
}
